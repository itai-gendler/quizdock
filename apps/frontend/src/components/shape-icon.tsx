/** The slot of an option known only by its shape: the colour it is paired with. */
const slotOfShape = (shape: string) => OPTION_ORDER.find((p) => p.shape === shape)?.color;

/**
 * The mark of an answer, sized by the text around it (1em). `slot`: the option's colour,
 * its slot in the quiz's theme (THEMING §2.2) — the theme may draw its own icon, filled by
 * the text colour through a mask, or letters or numbers instead (`index`: the option's
 * place in its question; else the slot's place in the default order).
 */
export function ShapeIcon({
  shape,
  slot,
  index,
  className,
}: {
  shape: string;
  slot?: string;
  index?: number;
  className?: string;
}) {
  const theme = useLiveTheme();
  const color = slot ?? slotOfShape(shape) ?? 'green';
  const icon = useSlotIcon(color);
  const markers = theme?.markers ?? 'icons';
  if (markers !== 'icons') {
    const n =
      index ??
      Math.max(
        0,
        OPTION_ORDER.findIndex((p) => p.color === color),
      );
    return (
      <span
        aria-hidden
        className={cn(
          'inline-grid size-[1em] shrink-0 place-items-center leading-none font-extrabold',
          className,
        )}
      >
        {markers === 'letters' ? String.fromCharCode(65 + n) : n + 1}
      </span>
    );
  }
  if (icon) {
    return (
      <span
        aria-hidden
        className={cn('inline-block size-[1em] shrink-0 bg-current align-[-0.125em]', className)}
        style={{
          maskImage: `url("${icon}")`,
          maskSize: 'contain',
          maskRepeat: 'no-repeat',
          maskPosition: 'center',
        }}
      />
    );
  }
  return (
    <svg
      viewBox="0 0 256 256"
      aria-hidden
      className={cn('inline-block size-[1em] shrink-0 fill-current align-[-0.125em]', className)}
    >
      <path d={GLYPHS[color] ?? GLYPHS.green} />
    </svg>
  );
}
